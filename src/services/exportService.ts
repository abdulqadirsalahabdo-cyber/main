import { Document, Packer, Paragraph, TextRun, HeadingLevel, AlignmentType, Table, TableRow, TableCell, WidthType, BorderStyle } from 'docx';

export async function exportContractToDocx(title: string, contractText: string, language: 'ar' | 'en' = 'ar'): Promise<void> {
  const isRtl = language === 'ar';
  const paragraphs: Paragraph[] = [];

  // Header Title
  paragraphs.push(
    new Paragraph({
      text: title,
      heading: HeadingLevel.TITLE,
      alignment: AlignmentType.CENTER,
      spacing: { after: 300, before: 100 },
    })
  );

  // Subtitle / Legal Notice
  paragraphs.push(
    new Paragraph({
      alignment: AlignmentType.CENTER,
      spacing: { after: 400 },
      children: [
        new TextRun({
          text: isRtl 
            ? 'مستند قانوني معتمد - صادر عن منصة محلل العقود الذكي وفقاً لأحكام القانون المصري'
            : 'Official Legal Document - Generated by Smart Contract Analyzer under Egyptian Law',
          italics: true,
          size: 20,
          color: '555555',
        }),
      ],
    })
  );

  // Split lines and parse clauses
  const lines = contractText.split('\n');
  for (const line of lines) {
    const trimmed = line.trim();
    if (!trimmed) {
      paragraphs.push(new Paragraph({ spacing: { after: 120 } }));
      continue;
    }

    const isHeading = trimmed.startsWith('البند') || trimmed.startsWith('Clause') || trimmed.startsWith('المادة') || trimmed.startsWith('تمهيد') || trimmed.startsWith('أولاً') || trimmed.startsWith('ثانياً');

    paragraphs.push(
      new Paragraph({
        alignment: isRtl ? AlignmentType.RIGHT : AlignmentType.LEFT,
        bidirectional: isRtl,
        spacing: { after: isHeading ? 160 : 120, before: isHeading ? 200 : 0 },
        children: [
          new TextRun({
            text: trimmed,
            bold: isHeading,
            size: isHeading ? 26 : 22,
            font: isRtl ? 'Cairo' : 'Calibri',
            color: isHeading ? '111827' : '1f2937',
          }),
        ],
      })
    );
  }

  // Signatures Table
  const signatureTable = new Table({
    width: { size: 100, type: WidthType.PERCENTAGE },
    borders: {
      top: { style: BorderStyle.SINGLE, size: 1, color: 'CCCCCC' },
      bottom: { style: BorderStyle.NONE },
      left: { style: BorderStyle.NONE },
      right: { style: BorderStyle.NONE },
      insideHorizontal: { style: BorderStyle.NONE },
      insideVertical: { style: BorderStyle.NONE },
    },
    rows: [
      new TableRow({
        children: [
          new TableCell({
            width: { size: 50, type: WidthType.PERCENTAGE },
            children: [
              new Paragraph({
                alignment: isRtl ? AlignmentType.RIGHT : AlignmentType.LEFT,
                spacing: { before: 200, after: 300 },
                children: [
                  new TextRun({
                    text: isRtl ? 'توقيع الطرف الأول (المؤجر / صاحب العمل / البائع):' : 'First Party Signature:',
                    bold: true,
                    size: 22,
                  }),
                ],
              }),
              new Paragraph({ text: isRtl ? 'الاسم: .................................................' : 'Name: .................................................' }),
              new Paragraph({ text: isRtl ? 'التوقيع: ..............................................' : 'Signature: ............................................' }),
              new Paragraph({ text: isRtl ? 'بصمة الإبهام: .......................................' : 'Thumbprint: ...........................................' }),
            ],
          }),
          new TableCell({
            width: { size: 50, type: WidthType.PERCENTAGE },
            children: [
              new Paragraph({
                alignment: isRtl ? AlignmentType.RIGHT : AlignmentType.LEFT,
                spacing: { before: 200, after: 300 },
                children: [
                  new TextRun({
                    text: isRtl ? 'توقيع الطرف الثاني (المستأجر / العامل / المشتري):' : 'Second Party Signature:',
                    bold: true,
                    size: 22,
                  }),
                ],
              }),
              new Paragraph({ text: isRtl ? 'الاسم: .................................................' : 'Name: .................................................' }),
              new Paragraph({ text: isRtl ? 'التوقيع: ..............................................' : 'Signature: ............................................' }),
              new Paragraph({ text: isRtl ? 'بصمة الإبهام: .......................................' : 'Thumbprint: ...........................................' }),
            ],
          }),
        ],
      }),
    ],
  });

  paragraphs.push(new Paragraph({ spacing: { before: 400 } }));

  const doc = new Document({
    sections: [
      {
        properties: {
          page: {
            margin: {
              top: 1440, // 1 inch
              right: 1440,
              bottom: 1440,
              left: 1440,
            },
          },
        },
        children: [...paragraphs, signatureTable],
      },
    ],
  });

  const blob = await Packer.toBlob(doc);
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  const safeFilename = title.replace(/[/\\?%*:|"<>]/g, '_').substring(0, 40);
  a.download = `${safeFilename}.docx`;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}

export function printOfficialDocument(): void {
  window.print();
}
